import path from 'node:path';
import fs from 'node:fs';
import {classes} from '../codegen-clients.js';

const OUT_BASE = path.join(import.meta.dirname, '../../workspaces/clients/js/client/src/generated');

const HEADER = '// Generated by bin/codegen-clients.js. Do not edit this file, change the server source instead.';

// Implemented by hand in the base class of the generated class.
const IGNORED = {
    Context: ['destroy'],
};

const BASE_CLASS = {
    Context: 'ContextBase',
};

const TYPES = {
    int: 'number',
    object: 'Record<string, any>',
    Page: 'any',
    Frame: 'any',
    Offset: 'any',
    WaitForOptions: 'any',
    ElementHandle: 'RemoteHandle',
    RemoteObject: 'RemoteHandle',
};

function mapType(type) {
    return type
        .split('|')
        .map(part => part.trim().replace(/^\(|\)$/g, ''))
        .map(part => {
            const isArray = part.endsWith('[]');
            const base = isArray ? part.slice(0, -2) : part;
            const mapped = TYPES[base] ?? base;

            return isArray ? `${mapped}[]` : mapped;
        })
        .filter((part, index, parts) => parts.indexOf(part) === index)
        .join('|');
}

function defaultValue({initializer, type}) {
    switch (initializer?.type) {
        case 'object':
            return JSON.stringify(Object.fromEntries((initializer.members ?? []).map(({key, value}) => [key, value])));
        case 'array':
            return '[]';
        case 'null':
            return 'null';
        case 'true':
            return 'true';
        case 'false':
            return 'false';
        case 'numeric':
            return initializer.value;
        case 'string':
            return JSON.stringify(initializer.value);
    }
}

function emitParameter(parameter) {
    const value = defaultValue(parameter);
    const type = mapType(parameter.type);

    if (value !== undefined) {
        return `${parameter.name}: ${type} = ${value}`;
    }

    return `${parameter.name}${parameter.isOptional ? '?' : ''}: ${type}`;
}

function emitMethod({name, parameters, returns}) {
    const returnType = [...new Set(returns.map(mapType))].join('|') || 'void';
    const signature = parameters.map(emitParameter).join(', ');
    const args = parameters.map(parameter => parameter.name).join(', ');

    return [
        `    ${name}(${signature}): Promise<${returnType}> {`,
        `        return this.callFunc('${name}', [${args}]);`,
        '    }',
    ].join('\n');
}

function emitClass(cls) {
    const methods = (cls.methods instanceof Map ? [...cls.methods.values()] : cls.methods)
        .filter(method => ! IGNORED[cls.name]?.includes(method.name));
    const base = BASE_CLASS[cls.name] ?? 'RemoteObject';
    const references = classes
        .map(other => other.name)
        .filter(name => name !== cls.name && methods.some(method => method.returns.includes(name)));

    const content = [
        HEADER,
        `import {${base}, type RemoteHandle} from '../RemoteObject';`,
        ...references.map(name => `import {type ${name}} from './${name}';`),
        '',
        `export class ${cls.name} extends ${base} {`,
        methods.map(emitMethod).join('\n\n'),
        '}',
        '',
    ].join('\n');

    fs.writeFileSync(path.join(OUT_BASE, `${cls.name}.ts`), content, 'utf8');
}

function emitIndex() {
    const content = [
        HEADER,
        `import {registerRemoteClass} from '../RemoteObject';`,
        ...classes.map(({name}) => `import {${name}} from './${name}';`),
        '',
        ...classes.map(({name}) => `registerRemoteClass('${name}', ${name});`),
        '',
        `export {${classes.map(({name}) => name).join(', ')}};`,
        '',
    ].join('\n');

    fs.writeFileSync(path.join(OUT_BASE, 'index.ts'), content, 'utf8');
}

export function generate() {
    fs.mkdirSync(OUT_BASE, {recursive: true});
    classes.forEach(emitClass);
    emitIndex();
}
